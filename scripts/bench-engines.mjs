// Measures single-thread engine throughput for every Runner preset (12 examples + Builder budget).
// Run from the repository root: node scripts/bench-engines.mjs
// Writes docs/benchmarks/engines-node.json and docs/benchmarks/engines-node.md.
import {writeFile,mkdir} from 'node:fs/promises'
import {cpus,platform,arch} from 'node:os'
import process from 'node:process'
import {performance} from 'node:perf_hooks'
import {presets,modelErrors} from '../src/experiments/library.js'
import {createExperiment,ENGINE_VERSION} from '../src/engine/index.js'
import {experiment} from '../src/domains/newExamples.js'

const tiers=[1000,10000,100000,1000000]
const repeats=5
const budgetMs=4000 // skip larger tiers once one repetition exceeds this

function runOnce(model) {
  const start=performance.now()
  let n
  if(model.kind){const run=createExperiment(model);run.advance(model.samples);n=run.summary().n}
  else{const run=experiment(model);run.step(model.samples);n=run.result().n}
  return {ms:performance.now()-start,n}
}

const rows=[]
for(const preset of presets()){
  const base=preset.model, id=base.kind??base.id
  let skip=null
  for(const samples of tiers){
    const model={...base,samples,seed:42}
    const errors=modelErrors(model)
    if(errors.length){rows.push({id,title:preset.title,samples,status:'exceeds model limit',detail:String(errors[0]?.message??errors[0])});continue}
    if(skip){rows.push({id,title:preset.title,samples,status:'skipped',detail:skip});continue}
    runOnce({...model,samples:Math.min(samples,1000)}) // warm-up
    const times=[]
    let completed=0
    for(let i=0;i<repeats;i++){const r=runOnce(model);times.push(r.ms);completed=r.n}
    times.sort((a,b)=>a-b)
    const median=times[Math.floor(repeats/2)]
    rows.push({id,title:preset.title,samples,status:'measured',completed,medianMs:+median.toFixed(2),maxMs:+times.at(-1).toFixed(2),
      replicationsPerSecond:Math.round(completed/(median/1000))})
    if(times.at(-1)>budgetMs) skip=`previous tier exceeded ${budgetMs} ms`
  }
}

const meta={date:new Date().toISOString(),node:process.version,cpu:cpus()[0].model,platform:platform()+' '+arch(),engineVersion:ENGINE_VERSION,
  method:`Single thread in Node, no worker or rendering. Each preset runs at its default parameters with seed 42 and the given replication count; ${repeats} repetitions after a warm-up, median and max wall time. A tier is skipped once a repetition exceeds ${budgetMs} ms. Browser worker startup and messaging are not included (see pi-browser.json for those costs).`}
await mkdir('docs/benchmarks',{recursive:true})
await writeFile('docs/benchmarks/engines-node.json',JSON.stringify({...meta,rows},null,2)+'\n')

const fmt=v=>v==null?'—':v.toLocaleString('en-US')
const ids=[...new Set(rows.map(r=>r.id))]
let md=`# Engine throughput (Node, single thread)\n\nGenerated by \`node scripts/bench-engines.mjs\` on ${meta.date.slice(0,10)} · ${meta.cpu} · ${meta.platform} · Node ${meta.node} · engine ${meta.engineVersion}.\n\n${meta.method}\n\nMedian wall time in ms per run (replications per second in parentheses).\n\n| Preset | ${tiers.map(fmt).join(' | ')} |\n| --- | ${tiers.map(()=> '---:').join(' | ')} |\n`
for(const id of ids){
  const cells=tiers.map(t=>{const r=rows.find(x=>x.id===id&&x.samples===t);return r.status==='measured'?`${fmt(r.medianMs)} (${fmt(r.replicationsPerSecond)}/s)`:r.status})
  md+=`| ${rows.find(r=>r.id===id).title} | ${cells.join(' | ')} |\n`
}
await writeFile('docs/benchmarks/engines-node.md',md)
console.log(md)
