import {test,expect} from '@playwright/test'

test('a nested cost formula replays and satisfies the risk challenge',async({page})=>{
  await page.goto('/#/builder')
  const app=page.locator('.builder')
  const button=name=>app.getByRole('button',{name,exact:true})
  await button('Table').click()
  await button('Add formula').click()
  await app.getByLabel('Expression for Derived value 1').fill('design + equipment')
  await app.getByLabel('Output formula').fill('derived1 + labor')
  await button('Run simulation').click()
  await expect(app.getByText('Completed run · Seed 42')).toBeVisible()
  await expect(app.getByText('Saved on this device')).toBeVisible()
  await page.reload()
  await expect(app.getByText('Completed run · Seed 42')).toBeVisible()
  await button('Table').click()
  await app.getByLabel('Expression for Derived value 1').fill('derived1 + labor')
  await expect(button('Run simulation')).toBeDisabled()
  await app.getByRole('button',{name:/^Validate \(/}).click()
  await expect(page.getByRole('dialog',{name:'Model validation'}).getByText(/Cycle at derived1/)).toBeVisible()
  await page.keyboard.press('Escape')
  await button('Undo').click()
  await expect(button('Run simulation')).toBeEnabled()
  await button('Export').click()
  const downloaded=page.waitForEvent('download')
  await page.getByRole('dialog',{name:'Export'}).getByRole('button',{name:/Run bundle/}).click()
  expect((await downloaded).suggestedFilename()).toMatch(/\.zip$/)
  await page.goto('/#/challenges/C11')
  await page.getByLabel('Saved project').selectOption({index:1})
  await page.getByRole('button',{name:'Check my model'}).click()
  await expect(page.getByText('Challenge completed',{exact:true})).toBeVisible()
  await page.reload()
  await expect(page.getByText('Attempt history (1)')).toBeVisible()
})

test('a Studio variable is applied once and is undoable',async({page})=>{
  await page.goto('/#/builder')
  const app=page.locator('.builder')
  await expect(app.getByRole('button',{name:'Run simulation',exact:true})).toBeEnabled()
  await app.getByRole('button',{name:'Table',exact:true}).click()
  const rows=app.locator('.bd-sheet-table').first().locator('tbody tr')
  await expect(rows).toHaveCount(3)
  await page.evaluate(()=>{
    const data={distribution:'uniform',a:3,b:7}
    sessionStorage.setItem('mc-studio-input',JSON.stringify(data))
    window.dispatchEvent(new CustomEvent('mc-studio-input',{detail:data}))
  })
  await expect(rows).toHaveCount(4)
  const added=rows.last()
  await expect(added.getByLabel('Display name')).toHaveValue('Uniform input')
  await expect(added.getByLabel('Minimum',{exact:true})).toHaveValue('3')
  await expect(added.getByLabel('Maximum',{exact:true})).toHaveValue('7')
  await app.getByRole('button',{name:'Undo',exact:true}).click()
  await expect(rows).toHaveCount(3)
})

test('Builder threshold controls include or exclude ties in a worker run',async({page})=>{
  await page.goto('/#/builder')
  const app=page.locator('.builder')
  const button=name=>app.getByRole('button',{name,exact:true})
  await button('Table').click()
  await app.getByLabel('Output formula').fill('design - design')
  await app.getByLabel('Threshold (EUR)',{exact:true}).fill('0')
  await app.getByLabel('Replications',{exact:true}).fill('10')
  for(const [op,hits] of [['>',0],['>=',10],['<',0],['<=',10]]){
    await app.getByLabel('Count an event when the output is').selectOption(op)
    await expect(app.getByText('Completed run · Seed 42')).toHaveCount(0)
    await button('Run simulation').click()
    await expect(app.getByText('Completed run · Seed 42')).toBeVisible()
    await expect(app.getByText(hits+' events observed',{exact:true})).toBeVisible()
  }
})
