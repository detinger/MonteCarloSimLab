import {test,expect} from '@playwright/test'
import {readFile} from 'node:fs/promises'

test('Runner executes the twelve example defaults and a Builder model through their workers',async({page})=>{
  await page.goto('/#/experiments')
  const view=page.locator('.runner-page:visible')
  const source=view.getByLabel('Model source')
  await expect(source.locator('optgroup[label="Example defaults"] option')).toHaveCount(13)
  const ids=await source.locator('optgroup[label="Example defaults"] option').evaluateAll(options=>options.map(o=>o.value))
  expect(ids).toHaveLength(13)
  for(const id of ids){
    await source.selectOption(id)
    await view.getByLabel('Replications',{exact:true}).fill('16')
    await view.getByRole('button',{name:'Run experiment'}).click()
    await expect(view.getByRole('status').filter({hasText:'complete · 16 of 16'})).toBeVisible()
  }
  await page.reload()
  await expect(view.getByRole('button',{name:'Reopen',exact:true})).toHaveCount(13)
  await view.getByRole('button',{name:'Reopen',exact:true}).first().click()
  await view.getByRole('link',{name:'Export this run'}).click()
  const center=page.locator('.runner-page:visible')
  await center.getByLabel('File format').selectOption('json')
  const [download]=await Promise.all([page.waitForEvent('download'),center.getByRole('button',{name:'Download file'}).click()])
  const manifest=JSON.parse(await readFile(await download.path(),'utf8'))
  expect(manifest.status).toBe('complete')
  expect(manifest.model.kind).toBe('builder')
  expect(manifest.summary.n).toBe(16)
})

test('Runner compares two real runs, validates settings and cancels a paused job',async({page})=>{
  await page.goto('/#/experiments')
  const view=page.locator('.runner-page:visible')
  const reps=view.getByLabel('Replications',{exact:true}),start=view.getByRole('button',{name:'Run experiment'})
  await reps.fill('')
  await expect(start).toBeDisabled()
  await reps.fill('80')
  await start.click()
  await expect(view.getByRole('status').filter({hasText:'complete · 80 of 80'})).toBeVisible()
  await view.getByLabel('Random seed').fill('5')
  await start.click()
  await expect(view.getByRole('button',{name:'Reopen',exact:true})).toHaveCount(2)
  await view.getByLabel('Compare with a saved result').selectOption({index:1})
  await expect(view.getByText('Difference in estimates',{exact:false})).toBeVisible()
  await view.getByLabel('Model source').selectOption('preset-queue')
  await reps.fill('70000')
  await start.click()
  await view.getByRole('button',{name:'Pause',exact:true}).click()
  await expect(view.getByRole('button',{name:'Resume'})).toBeVisible()
  await view.getByRole('button',{name:'Cancel',exact:true}).click()
  await expect(view.getByRole('status').filter({hasText:'cancelled'})).toBeVisible()
  await page.reload()
  await view.getByRole('button',{name:'Reopen',exact:true}).first().click()
  await expect(view.getByRole('status').filter({hasText:'cancelled'})).toBeVisible()
})

test('Export center uses the completed lab snapshot and reads the device save on reload',async({page})=>{
  await page.goto('/#/pi')
  await page.getByRole('button',{name:'Save run',exact:true}).click()
  await expect(page.getByText('Saved as the latest Pi run on this device.')).toBeVisible()
  await page.evaluate(()=>{location.hash='/exports'})
  const source=page.getByLabel('Export source')
  await source.selectOption('live-pi')
  await page.getByLabel('File format').selectOption('zip')
  await expect(page.getByText('model.json\nrun-manifest.json\nsummary.json\nanalysis.ipynb',{exact:true})).toBeVisible()
  await page.reload()
  await source.selectOption('saved-pi')
  await page.getByLabel('File format').selectOption('ipynb')
  const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Download file'}).click()])
  expect(JSON.parse(await readFile(await download.path(),'utf8')).nbformat).toBe(4)
})
